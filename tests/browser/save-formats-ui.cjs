const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { unzipSync } = require('fflate');
const root = path.resolve(__dirname, '../..');
const url = process.env.OFFICE_SAVE_URL || 'http://127.0.0.1:5198/';
const out = path.resolve(root, process.env.OFFICE_SAVE_OUTPUT || 'test-results/save-formats-ui');
fs.mkdirSync(out, { recursive: true });
const report = { checks: [], errors: [], externalRequests: [] };
let browser;
(async () => { try {
  browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  const page = await browser.newPage({ viewport: { width: 1360, height: 950 }, acceptDownloads: true });
  page.setDefaultTimeout(30000);
  page.on('pageerror', e => report.errors.push(e.message));
  page.on('request', r => { if (/^https?:/.test(r.url()) && new URL(r.url()).origin !== new URL(url).origin) report.externalRequests.push(r.url()); });
  const downloads=[];page.on('download',d=>downloads.push(d.suggestedFilename()));
  await page.goto(url);
  await page.getByTestId('document-open-input').setInputFiles(path.join(root, 'tests/compatibility/presentation-typography/spacing-baseline.pptx'));
  await page.locator('[data-testid="standalone-presentation-editor"][data-ready="true"]').waitFor();
  const dialog=page.getByTestId('save-format-dialog');
  await page.keyboard.press('Control+Shift+s');await dialog.waitFor();
  assert.equal(await dialog.getByRole('radio').count(),2);
  assert.equal(await page.getByTestId('save-format-pptx').isChecked(),true);
  await page.getByTestId('save-format-name').fill('../invalid');
  await page.getByTestId('save-format-confirm').click();
  await dialog.getByRole('alert').filter({hasText:'文件名'}).waitFor();
  assert.equal(downloads.length,0);
  await page.keyboard.press('Escape');await dialog.waitFor({state:'hidden'});
  assert.match(await page.locator('.save-state').innerText(),/尚未保存/);
  report.checks.push('Keyboard Save As offers only supported PPTX/PDF; invalid name produces no download and Escape preserves unsaved state');
  await page.getByRole('button',{name:'另存为',exact:true}).click();
  await page.getByTestId('save-format-pdf').check();
  await page.getByTestId('save-format-name').fill('排版副本.v2');
  await page.screenshot({path:path.join(out,'save-format-dialog.png')});
  let pending=page.waitForEvent('download',{timeout:120000});
  await page.getByTestId('save-format-confirm').click();
  let downloaded=await pending;assert.equal(downloaded.suggestedFilename(),'排版副本.v2.pdf');
  await downloaded.saveAs(path.join(out,'format-copy.pdf'));
  await dialog.waitFor({state:'hidden'});
  assert.equal(fs.readFileSync(path.join(out,'format-copy.pdf')).subarray(0,5).toString(),'%PDF-');
  assert.match(await page.locator('.titlebar-context').innerText(),/spacing-baseline.pptx/);
  assert.match(await page.locator('.save-state').innerText(),/尚未保存/);
  report.checks.push('Actual PDF export honors the chosen filename while retaining the editable PPTX and its unsaved state');
  await page.getByRole('button',{name:'另存为',exact:true}).click();
  assert.equal(await page.getByTestId('save-format-pptx').isChecked(),true);
  await page.getByTestId('save-format-name').fill('重命名后.v2');
  pending=page.waitForEvent('download');await page.getByTestId('save-format-confirm').click();
  downloaded=await pending;assert.equal(downloaded.suggestedFilename(),'重命名后.v2.pptx');
  await downloaded.saveAs(path.join(out,'renamed.pptx'));await dialog.waitFor({state:'hidden'});
  assert.ok(unzipSync(fs.readFileSync(path.join(out,'renamed.pptx')))['ppt/presentation.xml']);
  await page.locator('.titlebar-context').filter({hasText:'重命名后.v2.pptx'}).waitFor();
  assert.match(await page.locator('.save-state').innerText(),/^已保存$/);
  pending=page.waitForEvent('download');await page.getByRole('button',{name:'保存',exact:true}).click();
  assert.equal((await pending).suggestedFilename(),'重命名后.v2.pptx');
  report.checks.push('Same-format Save As produces a real PPTX and marks it saved; later Save retains the new filename');
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'另存为',exact:true}).click();
  assert.equal(await dialog.evaluate(n=>n.scrollWidth<=n.clientWidth+1),true);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true);
  await page.getByTestId('save-format-confirm').focus();await page.keyboard.press('Tab');
  assert.equal(await page.getByTestId('save-format-name').evaluate(n=>n===document.activeElement),true);
  const before=downloads.length;await page.keyboard.press('Control+s');
  assert.equal(await dialog.isVisible(),true);assert.equal(downloads.length,before);
  await page.screenshot({path:path.join(out,'save-format-mobile.png')});
  await page.getByTestId('save-format-cancel').click();
  report.checks.push('390px dialog has no horizontal overflow, traps Tab focus and prevents background Save shortcuts');
  assert.deepEqual(report.errors,[]);assert.deepEqual(report.externalRequests,[]);report.ok=true;
} catch(error){report.ok=false;report.error=error.stack;process.exitCode=1;console.error(error);}
finally{await browser?.close();fs.writeFileSync(path.join(out,'report.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report));}})();
