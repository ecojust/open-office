// Real production UI; no application internals or dev-only imports.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { unzipSync, strFromU8 } = require('fflate');
const root = path.resolve(__dirname, '../..');
const url = process.env.PRESENTATION_URL || 'http://127.0.0.1:4198/';
const out = path.resolve(root, process.env.PRESENTATION_RANGE_UI_OUTPUT || 'test-results/presentation-range-ui');
fs.mkdirSync(out, { recursive: true });
const report = { scope: 'Real selection dialog, undo/redo, save and reopen without private APIs', checks: [], errors: [], externalRequests: [] };
let browser;
(async () => { try {
  browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  page.setDefaultTimeout(30000);
  page.on('pageerror', e => report.errors.push(e.message));
  page.on('request', r => { if (/^https?:/.test(r.url()) && new URL(r.url()).origin !== new URL(url).origin) report.externalRequests.push(r.url()); });
  await page.goto(url);
  const open = async file => {
    await page.getByTestId('document-open-input').setInputFiles(file);
    await page.locator('.titlebar-context').filter({ hasText: path.basename(file) }).waitFor();
    await page.locator('[data-testid="standalone-presentation-editor"][data-ready="true"]').waitFor();
    await page.locator('[data-testid="presentation-slide-thumbnail"][data-slide-index="1"]').click();
    await page.locator('[data-testid="presentation-object"][aria-label^="BASELINE_EXPLICIT，"]').click();
  };
  const scene = () => page.getByTestId('presentation-stage').locator('svg').first().innerHTML();
  const dialog = () => page.getByRole('dialog', { name: '局部文字格式', exact: true });
  const select = async (start, end) => {
    const input = page.getByTestId('presentation-range-input');
    await input.focus();
    await input.evaluate((node, range) => { node.setSelectionRange(...range); node.dispatchEvent(new Event('select', { bubbles: true })); }, [start, end]);
  };
  await open(path.join(root, 'tests/compatibility/presentation-typography/spacing-baseline.pptx'));
  const original = await scene();
  await page.getByTestId('presentation-range-format').click();
  assert.equal(await page.getByTestId('presentation-range-input').getAttribute('readonly'), '');
  assert.equal(await page.getByTestId('presentation-range-input').inputValue(), 'Normal Raised Lowered Zero');
  assert.equal(await page.getByTestId('presentation-range-apply').isDisabled(), true);
  await select(9, 17);
  assert.equal(await page.getByTestId('presentation-range-apply').isDisabled(), true);
  await page.getByTestId('presentation-range-bold').selectOption('true');
  assert.equal(await page.getByTestId('presentation-range-apply').isEnabled(), true);
  let unexpectedDownload = false;
  const blockDownload = () => { unexpectedDownload = true; };
  page.on('download', blockDownload);
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.getByText('局部文字格式还有未确认的输入。', { exact: false }).first().waitFor();
  assert.equal(await dialog().isVisible(), true);
  assert.equal(unexpectedDownload, false);
  page.off('download', blockDownload);
  await page.getByTestId('presentation-range-cancel').click();
  while (await page.getByRole('button', { name: '关闭错误提示', exact: true }).count()) await page.getByRole('button', { name: '关闭错误提示', exact: true }).first().click();
  assert.equal(await scene(), original);
  report.checks.push('No selection or no explicit style disables Apply; pending selection format blocks Save; Cancel preserves the scene');
  await page.getByTestId('presentation-range-format').click();
  await select(9, 17);
  await page.getByTestId('presentation-range-bold').selectOption('true');
  await page.screenshot({ path: path.join(out, 'range-dialog.png') });
  await page.getByTestId('presentation-range-apply').click();
  await dialog().waitFor({ state: 'hidden' });
  const edited = await scene();
  assert.notEqual(edited, original);
  report.checks.push('Apply formats a selection crossing two differently colored, raised/lowered runs');
  await page.getByTestId('standalone-presentation-editor').focus();
  await page.keyboard.press('Control+z');
  assert.equal(await scene(), original);
  await page.keyboard.press('Control+Shift+z');
  assert.equal(await scene(), edited);
  report.checks.push('One keyboard undo/redo restores the complete mixed-format scene');
  // Number inputs coerce v-model values to numbers: exercise that real UI path.
  await page.getByTestId('presentation-range-format').click();
  await select(0, 6);
  await page.getByTestId('presentation-range-font').fill('Arial');
  await page.getByTestId('presentation-range-size').fill('20.5');
  await page.getByTestId('presentation-range-italic').selectOption('true');
  await page.getByTestId('presentation-range-underline').selectOption('true');
  await page.getByTestId('presentation-range-color-enabled').check();
  await page.getByTestId('presentation-range-color').fill('#ee7700');
  await page.getByTestId('presentation-range-apply').click();
  await dialog().waitFor({ state: 'hidden' });
  await page.screenshot({ path: path.join(out, 'range-edited.png') });
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  const saved = path.join(out, 'range-edited.pptx');
  await (await download).saveAs(saved);
  const parts = unzipSync(fs.readFileSync(saved));
  const properties = await page.evaluate(xml => {
    const a = 'http://schemas.openxmlformats.org/drawingml/2006/main';
    const document = new DOMParser().parseFromString(xml, 'application/xml');
    const shape = [...document.getElementsByTagNameNS('*', 'sp')].find(s => s.getElementsByTagNameNS('*', 'cNvPr')[0]?.getAttribute('name') === 'BASELINE_EXPLICIT');
    return [...shape.getElementsByTagNameNS(a, 'r')].flatMap(r => {
      const props = r.getElementsByTagNameNS(a, 'rPr')[0], text = r.getElementsByTagNameNS(a, 't')[0].textContent;
      return text.split('').map(char => ({ char, bold: props.getAttribute('b'), italic: props.getAttribute('i'), underline: props.getAttribute('u'), size: props.getAttribute('sz'), baseline: props.getAttribute('baseline'), color: props.getElementsByTagNameNS(a, 'srgbClr')[0]?.getAttribute('val'), font: props.getElementsByTagNameNS(a, 'latin')[0]?.getAttribute('typeface') }));
    });
  }, strFromU8(parts['ppt/slides/slide2.xml']));
  assert.equal(properties.map(p => p.char).join(''), 'Normal Raised Lowered Zero');
  properties.forEach((p, i) => {
    assert.equal(p.baseline, i < 7 ? '0' : i < 14 ? '30000' : i < 22 ? '-25000' : '0');
    assert.equal(['1', 'true'].includes(p.bold), i >= 9 && i < 17);
    assert.equal(p.size, i < 6 ? '2050' : '2600');
    assert.equal(p.color.toUpperCase(), i < 6 ? 'EE7700' : i < 7 ? '202020' : i < 14 ? 'B51D46' : i < 22 ? '1565A8' : '248046');
    assert.equal(['1', 'true'].includes(p.italic), i < 6);
    assert.equal(p.underline === 'sng', i < 6);
    assert.equal(p.font, 'Arial');
  });
  report.checks.push('Real download XML changes all six supported properties only in intended character ranges; original baseline/color outside them remains intact');
  const finalScene = await scene();
  await open(saved);
  assert.equal(await scene(), finalScene);
  await page.getByTestId('presentation-range-format').click();
  assert.equal(await page.getByTestId('presentation-range-input').inputValue(), 'Normal Raised Lowered Zero');
  await page.keyboard.press('Escape');
  await dialog().waitFor({ state: 'hidden' });
  report.checks.push('Saved file reopens with the same rendered scene and editable selection; Escape cancels');
  assert.deepEqual(report.errors, []); assert.deepEqual(report.externalRequests, []);
  report.ok = true;
} catch (error) { report.ok = false; report.error = error.stack; process.exitCode = 1; console.error(error); }
finally { await browser?.close(); fs.writeFileSync(path.join(out, 'report.json'), JSON.stringify(report, null, 2)); console.log(JSON.stringify(report)); } })();
