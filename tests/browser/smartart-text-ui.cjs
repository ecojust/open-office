const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { unzipSync, strFromU8 } = require('fflate');
const root = path.resolve(__dirname, '../..');
const out = path.join(root, 'test-results/smartart-text-ui');
fs.mkdirSync(out, { recursive: true });
const report = { checks: [], errors: [] };
const nodeId = '{DB1843D3-471D-3D4F-8D9B-C7F506BC5FEE}';
const contentId = '{63986E3B-5608-7F48-A1F2-C2D1F88EED58}';
let browser;
(async () => { try {
  browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  page.setDefaultTimeout(30000);
  await page.routeWebSocket('**', () => {});
  page.on('pageerror', error => report.errors.push(error.message));
  await page.goto('http://127.0.0.1:5198/');
  async function open(file) {
    await page.getByTestId('document-open-input').setInputFiles(file);
    await page.locator('.titlebar-context').filter({ hasText: path.basename(file) }).waitFor();
    await page.locator('[data-testid="standalone-presentation-editor"][data-ready="true"]').waitFor();
  }
  const api = (method, value) => page.evaluate(async ({method,value}) => document.querySelector('[data-testid="standalone-presentation-editor"]').__vueParentComponent.exposed[method](value), {method,value});
  const node = () => page.locator(`[data-testid="presentation-smartart-node"][data-node-id="${nodeId}"]`);
  const object = () => page.locator('[data-testid="presentation-object"][data-kind="unknown"]');
  const picture = () => page.getByTestId('presentation-stage').locator('svg image').first().getAttribute('href');
  await open(path.join(root, 'tests/compatibility/presentation-complex/fixtures/upstream/apache-poi/smartart-simple.pptx'));
  await object().click();
  await node().waitFor();
  assert.equal(await node().isEnabled(), true);
  assert.equal(await page.getByTestId('presentation-width').isDisabled(), true);
  const originalPreview = await picture();
  const before = await api('getPresentationState');
  await node().click();
  await page.getByTestId('presentation-smartart-input').fill('SHOULD NOT SAVE');
  const rejected = await page.evaluate(async () => { try { await document.querySelector('[data-testid="standalone-presentation-editor"]').__vueParentComponent.exposed.exportFile(); return ''; } catch (error) { return error.message; } });
  assert.match(rejected, /节点文字/);
  await page.getByTestId('presentation-smartart-cancel').click();
  assert.equal((await api('getPresentationState')).revision, before.revision);
  assert.equal(await picture(), originalPreview);
  report.checks.push('Unapplied node drafts block export; cancel leaves revision and preview unchanged');
  await node().click();
  await page.getByTestId('presentation-smartart-input').fill('Plan Q4');
  await page.screenshot({ path: path.join(out, 'node-dialog.png') });
  await page.getByTestId('presentation-smartart-apply').click();
  await page.getByRole('dialog', { name: '编辑图示节点文字' }).waitFor({ state: 'hidden' });
  await page.waitForFunction(({id}) => [...document.querySelectorAll('[data-testid="presentation-smartart-node"]')].find(n => n.dataset.nodeId === id)?.textContent.includes('Plan Q4'), {id:nodeId});
  assert.notEqual(await picture(), originalPreview);
  assert.equal((await api('getPresentationState')).revision, before.revision + 1);
  assert.equal(await page.getByTestId('presentation-width').isDisabled(), true);
  report.checks.push('Actual Vue apply updates node list and rendered preview atomically while geometry stays protected');
  await page.getByTestId('standalone-presentation-editor').focus();
  await page.keyboard.press('Control+z');
  await page.waitForFunction(({id}) => [...document.querySelectorAll('[data-testid="presentation-smartart-node"]')].find(n => n.dataset.nodeId === id)?.textContent.includes('abc'), {id:nodeId});
  assert.equal(await picture(), originalPreview);
  await page.keyboard.press('Control+Shift+z');
  await page.waitForFunction(({id}) => [...document.querySelectorAll('[data-testid="presentation-smartart-node"]')].find(n => n.dataset.nodeId === id)?.textContent.includes('Plan Q4'), {id:nodeId});
  report.checks.push('Keyboard undo/redo restores both preview and node text');
  await page.screenshot({ path: path.join(out, 'edited-node.png') });
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  const saved = path.join(out, 'edited.pptx');
  await (await download).saveAs(saved);
  const parts = unzipSync(fs.readFileSync(saved));
  const result = await page.evaluate(({data,drawing,nodeId,contentId}) => {
    const read = xml => new DOMParser().parseFromString(xml, 'application/xml');
    const d = read(data), c = read(drawing);
    const point = [...d.getElementsByTagNameNS('*', 'pt')].find(n => n.getAttribute('modelId') === contentId);
    const shape = [...c.getElementsByTagNameNS('*', 'sp')].find(n => n.getAttribute('modelId') === nodeId);
    const text = parent => [...parent.getElementsByTagNameNS('http://schemas.openxmlformats.org/drawingml/2006/main', 't')].map(n => n.textContent).join('');
    return { data:text(point), cache:text(shape) };
  }, {data:strFromU8(parts['ppt/diagrams/data1.xml']),drawing:strFromU8(parts['ppt/diagrams/drawing1.xml']),nodeId,contentId});
  assert.deepEqual(result, {data:'Plan Q4',cache:'Plan Q4'});
  report.checks.push('Real Save download updates independently identified data and cache nodes');
  await open(saved);
  await object().click();
  assert.match(await node().innerText(), /Plan Q4/);
  await node().click();
  assert.equal(await page.getByTestId('presentation-smartart-input').inputValue(), 'Plan Q4');
  await page.keyboard.press('Escape');
  await page.getByRole('dialog', { name: '编辑图示节点文字' }).waitFor({state:'hidden'});
  report.checks.push('Saved file reopens editable with changed text; Escape closes without mutation');
  assert.deepEqual(report.errors, []);
  report.ok = true;
} catch(error) { report.ok = false; report.error = error.stack; process.exitCode = 1; console.error(error); }
finally { await browser?.close(); fs.writeFileSync(path.join(out, 'report.json'), JSON.stringify(report,null,2)); console.log(JSON.stringify(report)); } })();
