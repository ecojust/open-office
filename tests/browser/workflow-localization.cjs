/* Real workflow components: live language changes preserve source, folds and session history. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');
const root = path.resolve(__dirname, '../..');
const output = path.join(root, 'test-results/workflow-localization');
fs.mkdirSync(output, { recursive: true });
const harnessPath = path.join(output, 'harness.ts');
fs.writeFileSync(harnessPath, `
import { createApp, h, ref, nextTick } from 'vue';
import WorkflowEditor from '/src/components/WorkflowEditor.vue';
import { locale } from '/src/shared/i18n.ts';
import { createDocument, serializeDocument } from '/src/workflow/core/documents.ts';
import { bytesToBase64 } from '/src/shared/document.ts';
const source = 'flowchart TD\\r\\n  subgraph 保留中文\\r\\n    A[开始] --> B[结束]\\r\\n  end\\r\\n';
const diagram = createDocument('mermaid'); diagram.source = source; diagram.title = '中文图表';
const native = { id: 'diagram-localization', kind: 'diagram', name: '中文图表.owflow', extension: 'owflow', base64: bytesToBase64(new TextEncoder().encode(serializeDocument(diagram))) };
const boardNative = { id: 'canvas-localization', kind: 'canvas', name: '中文画布.owflow', extension: 'owflow' };
const handle = ref(), board = ref(), ready = ref(0);
window.qa = { locale, handle, board, source, ready, nextTick };
createApp({ setup: () => () => h('div', [h('div', { style: 'height:700px' }, h(WorkflowEditor, { ref: handle, document: native, onReady: () => ready.value++ })), h('div', { style: 'height:700px' }, h(WorkflowEditor, { ref: board, document: boardNative, onReady: () => ready.value++ }))]) }).mount('#app');
`);
let server, browser;
(async () => {
  const errors = [];
  try {
    const { createServer } = await import('vite');
    server = await createServer({ root, clearScreen: false, cacheDir: path.join(output, 'vite-cache'), server: { host: '127.0.0.1', port: 0, hmr: false, watch: { ignored: ['**/vendor/**', '**/target/**', '**/.build/**', '**/test-results/**'] } } });
    await server.listen();
    browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || '/usr/bin/chromium', args: ['--no-sandbox', '--disable-dev-shm-usage'] });
    const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
    page.on('pageerror', error => errors.push(error.message));
    const origin = `http://127.0.0.1:${server.httpServer.address().port}`;
    await page.route('**/__workflow-localization', route => route.fulfill({ contentType: 'text/html', body: '<!doctype html><html><body><div id="app"></div><script type="module" src="/test-results/workflow-localization/harness.ts"></script></body></html>' }));
    await page.goto(origin + '/__workflow-localization');
    await page.waitForFunction(() => window.qa?.ready.value === 2);
    const diagram = page.locator('[data-document-id="diagram-localization"]');
    const source = diagram.getByTestId('diagram-source');
    assert.equal(await source.getAttribute('aria-label'), '代码图表源码');
    const original = await page.evaluate(async () => {
      const qa = window.qa, element = document.querySelector('[data-testid="diagram-source"]');
      qa.sourceElement = element; qa.handleInstance = qa.handle.value;
      qa.sourceComponent = element.closest('.diagram-source-editor').__vueParentComponent.exposed;
      return { model: await qa.handle.value.inspectModel(), state: await qa.handle.value.inspect() };
    });
    await diagram.locator('.cm-foldGutter .cm-gutterElement').filter({ hasText: '⌄' }).first().click();
    await diagram.locator('.cm-foldPlaceholder').waitFor();
    await page.evaluate(async () => { window.qa.locale.value = 'en'; await window.qa.nextTick(); });
    assert.equal(await source.getAttribute('aria-label'), 'Code diagram source');
    assert.equal(await diagram.locator('.cm-foldPlaceholder').getAttribute('aria-label'), 'Unfold code block');
    assert.equal(await diagram.locator('.cm-foldPlaceholder').getAttribute('title'), 'Unfold code block');
    assert.equal(await diagram.getByTestId('diagram-template-toggle').textContent(), 'Diagram templates');
    assert.equal(await page.evaluate(() => document.querySelector('[data-testid="diagram-source"]') === window.qa.sourceElement && window.qa.handle.value === window.qa.handleInstance), true);
    assert.deepEqual(await page.evaluate(async () => ({ model: await window.qa.handle.value.inspectModel(), state: await window.qa.handle.value.inspect() })), original);
    assert.equal(await page.evaluate(() => window.qa.sourceComponent.value), original.model.source);
    await diagram.getByTestId('diagram-template-toggle').click();
    await diagram.getByRole('searchbox', { name: 'Search diagram templates' }).fill('Layered delivery');
    assert.equal(await diagram.locator('[data-testid="diagram-template-library"] .diagram-template-card').count(), 1);
    assert.match(await diagram.locator('.diagram-template-card').textContent(), /Layered delivery and approval/);
    await diagram.getByRole('button', { name: 'Close diagram templates', exact: true }).click();
    await diagram.getByTestId('diagram-style-toggle').click();
    await diagram.locator('[data-diagram-style="blueprint"]').click();
    await diagram.getByRole('button', { name: 'Done', exact: true }).click();
    const changed = await page.evaluate(async () => ({ model: await window.qa.handle.value.inspectModel(), state: await window.qa.handle.value.inspect() }));
    assert.equal(changed.model.diagramStyle, 'blueprint'); assert.equal(changed.state.canUndo, true);
    await page.evaluate(async () => { window.qa.locale.value = 'zh-CN'; await window.qa.nextTick(); });
    assert.deepEqual(await page.evaluate(async () => ({ model: await window.qa.handle.value.inspectModel(), state: await window.qa.handle.value.inspect() })), changed);
    assert.equal(await diagram.locator('.cm-foldPlaceholder').getAttribute('aria-label'), '展开代码块');
    await page.evaluate(async () => { await window.qa.handle.value.undo(); });
    assert.equal((await page.evaluate(() => window.qa.handle.value.inspectModel())).diagramStyle, original.model.diagramStyle);
    const canvas = page.locator('[data-document-id="canvas-localization"]');
    await canvas.getByTestId('board-template-toggle').click();
    await page.evaluate(async () => { window.qa.locale.value = 'en'; await window.qa.nextTick(); });
    assert.equal(await canvas.getByRole('region', { name: 'Canvas templates' }).count(), 1);
    assert.equal(await canvas.getByRole('button', { name: 'Insert Brainstorm template', exact: true }).count(), 1);
    await canvas.getByRole('button', { name: 'Insert Brainstorm template', exact: true }).click();
    const canvasBefore = await page.evaluate(async () => ({ model: await window.qa.board.value.inspectModel(), state: await window.qa.board.value.inspect() }));
    assert.ok(canvasBefore.model.scene.elements.some(element => /[\p{Script=Han}]/u.test(element.text || '')));
    await page.evaluate(async () => { window.qa.locale.value = 'zh-CN'; await window.qa.nextTick(); });
    assert.deepEqual(await page.evaluate(async () => ({ model: await window.qa.board.value.inspectModel(), state: await window.qa.board.value.inspect() })), canvasBefore);
    await page.evaluate(async () => {
      await window.qa.handle.value.mcpExecute('diagram_set_source', { source: 'pie\n  "删除": 1\n  "删除": 2' }, () => {});
      window.qa.locale.value = 'en'; await window.qa.nextTick();
    });
    await diagram.getByTestId('diagram-error').waitFor();
    assert.match(await diagram.getByTestId('diagram-error').textContent(), /Line 3: Duplicate pie chart category “删除”\./);
    const invalid = await page.evaluate(async () => ({ model: await window.qa.handle.value.inspectModel(), state: await window.qa.handle.value.inspect() }));
    await page.evaluate(async () => { window.qa.locale.value = 'zh-CN'; await window.qa.nextTick(); });
    assert.match(await diagram.getByTestId('diagram-error').textContent(), /第 3 行：饼图分类“删除”重复。/);
    assert.deepEqual(await page.evaluate(async () => ({ model: await window.qa.handle.value.inspectModel(), state: await window.qa.handle.value.inspect() })), invalid);
    assert.equal(errors.length, 0, errors.join('\n'));
    console.log('Workflow localization: PASS (live source/fold labels, same editor instance, source bytes, template search, canvas data, style undo history, translated diagnostics with original source tokens).');
  } finally { await browser?.close(); await server?.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
